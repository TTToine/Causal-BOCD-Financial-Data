import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
from scipy.stats import t
from scipy.special import logsumexp
import matplotlib.patches as mpatches
import matplotlib.colors as mcolors

# 1. Caricamento Dati e Simulazione Dollar Bars
# Scarichiamo i dati storici dell'S&P 500
data_raw = yf.download("^GSPC", start="2000-01-01", end="2024-12-31", progress=False, auto_adjust=True)
if isinstance(data_raw.columns, pd.MultiIndex):
    data_raw.columns = data_raw.columns.get_level_values(0)

# Calcoliamo il volume in dollari per creare le 'Dollar Bars'
dollar_vol = (data_raw['Close'] * data_raw['Volume']).fillna(0)
v_target = dollar_vol.mean() * 1.5 # Soglia di volume per ogni bar
cum_vol = dollar_vol.cumsum().values

# Campionamento basato sul volume anziché sul tempo (rimuove il rumore intraday)
indices = [0]
last_threshold = 0
for i in range(1, len(cum_vol)):
    if cum_vol[i] - last_threshold >= v_target:
        indices.append(i)
        last_threshold = cum_vol[i]

data_sampled = data_raw.iloc[indices]
returns = 100 * np.log(data_sampled['Close'] / data_sampled['Close'].shift(1)).dropna().values
dates = data_sampled.index[1:]
T = len(returns)

# 2. Configurazione BOCD (Bayesian Online Changepoint Detection)
# Iperparametri dei priori Normal-Gamma
mu_0, kappa_0, alpha_0, beta_0 = 0.0, 1.0, 2.0, 1.0
# Parametri della Hazard Function (Power-Law)
gamma, lambda_h = 0.5, 50.0
R_max = 250 # Limite massimo della memoria (run-length) per efficienza

# Inizializzazione matrici per le probabilità
log_P_r = np.full((T, R_max + 1), -np.inf)
log_P_r[0, 0] = 0.0 # Al tempo 0, la run-length è sicuramente 0

# Parametri correnti del modello per ogni possibile run-length
mu, kappa = np.full(R_max + 1, mu_0), np.full(R_max + 1, kappa_0)
alpha, beta = np.full(R_max + 1, alpha_0), np.full(R_max + 1, beta_0)
nlpd_series = []

# Ciclo Principale: Elaborazione sequenziale dei dati
for t_idx in range(T):
    xt = returns[t_idx]
    r_limit = min(t_idx, R_max)

    # 1. Calcolo Likelihood Predittiva (Distribuzione Student-t)
    var_p = (beta[:r_limit+1] * (kappa[:r_limit+1] + 1)) / (alpha[:r_limit+1] * kappa[:r_limit+1])
    log_lik = t.logpdf(xt, df=2*alpha[:r_limit+1], loc=mu[:r_limit+1], scale=np.sqrt(var_p))

    # 2. Calcolo Hazard (Probabilità di avere un changepoint)
    r_range = np.arange(r_limit + 1)
    h_val = 1.0 / (lambda_h + r_range**gamma)
    log_H, log_1minusH = np.log(h_val), np.log(1 - h_val)

    # 3. Aggiornamento delle Probabilità Congiunte
    log_new_P_joint = np.full(r_limit + 2, -np.inf)
    # Caso: Il regime continua (run-length cresce)
    log_new_P_joint[1:r_limit+2] = log_P_r[t_idx, :r_limit+1] + log_1minusH + log_lik
    # Caso: Changepoint (la run-length torna a 0)
    log_new_P_joint[0] = logsumexp(log_P_r[t_idx, :r_limit+1] + log_H + log_lik)

    # 4. Calcolo Evidence e Normalizzazione (Posterior)
    log_evidence = logsumexp(log_new_P_joint)
    if t_idx + 1 < T:
        log_P_r[t_idx + 1, :min(t_idx+2, R_max+1)] = log_new_P_joint[:min(t_idx+2, R_max+1)] - log_evidence
        log_P_r[t_idx + 1, :R_max+1] -= logsumexp(log_P_r[t_idx + 1, :R_max+1])

    nlpd_series.append(-log_evidence) # Metrica di errore: Negative Log-Predictive Density

    # 5. Aggiornamento dei Parametri (Bayesian Learning)
    old_mu, old_kappa = mu[:r_limit+1].copy(), kappa[:r_limit+1].copy()
    old_alpha, old_beta = alpha[:r_limit+1].copy(), beta[:r_limit+1].copy()
    upd_len = min(r_limit + 1, R_max)

    # Aggiornamento ricorsivo dei parametri per ogni run-length
    mu[1:upd_len+1] = (old_kappa[:upd_len] * old_mu[:upd_len] + xt) / (old_kappa[:upd_len] + 1)
    kappa[1:upd_len+1] = old_kappa[:upd_len] + 1
    alpha[1:upd_len+1] = old_alpha[:upd_len] + 0.5
    beta[1:upd_len+1] = old_beta[:upd_len] + (old_kappa[:upd_len] * (xt - old_mu[:upd_len])**2) / (2 * (old_kappa[:upd_len] + 1))

    # Reset dei parametri per la run-length 0 ai valori dei priori
    mu[0], kappa[0], alpha[0], beta[0] = mu_0, kappa_0, alpha_0, beta_0

# 3. Plotting dei Risultati
filenames = ['sp500_dollar_bars.png', 'run_length_posterior.png', 'changepoint_probability_linear.png', 'changepoint_probability_log.png', 'nlpd_analysis.png']
fig, axes = plt.subplots(5, 1, figsize=(16, 22), sharex=True)

def save_subfig(ax, filename):
    extent = ax.get_tightbbox(fig.canvas.get_renderer()).transformed(fig.dpi_scale_trans.inverted())
    fig.savefig(filename, bbox_inches=extent, dpi=300)

# Prezzi di chiusura
axes[0].plot(dates, data_sampled['Close'].iloc[1:], color='black', label='S&P 500 (Dollar Bars)')

# Heatmap della Run-length Posterior (Distribuzione di probabilità dei regimi)
pos = axes[1].pcolormesh(dates, np.arange(R_max + 1), np.exp(log_P_r).T,
                         cmap='magma', shading='auto',
                         norm=mcolors.LogNorm(vmin=0.0001, vmax=1))
magma_patch = mpatches.Patch(color='#FDB42F', label='Run-length Posterior (Log-scaled)')
axes[1].legend(handles=[magma_patch], loc='upper right')
axes[1].set_ylabel("Run-length")

# Probabilità di Changepoint (Lineare e Logaritmica)
axes[2].plot(dates[1:], np.exp(log_P_r[1:, 0]), color='red', label='P(Changepoint) - Linear')
axes[3].plot(dates[1:], log_P_r[1:, 0], color='darkred', label='Log-P(Changepoint)')

# Analisi NLPD (Metrica di performance predittiva)
axes[4].plot(dates, nlpd_series, color='purple', alpha=0.3, label='NLPD')
axes[4].plot(dates, pd.Series(nlpd_series).rolling(50).mean(), color='darkblue', label='NLPD Trend')

for i, ax in enumerate(axes):
    if i != 1: ax.legend(loc='upper right')
    ax.grid(True, alpha=0.2)
    plt.tight_layout()
    save_subfig(ax, filenames[i])

plt.show()